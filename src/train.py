"""Train, compare, evaluate (repeated cross-validation) and save the screening model.

Usage: python -m src.train
"""
import json
from datetime import date
from pathlib import Path

import joblib
import numpy as np
import sklearn
from sklearn.ensemble import HistGradientBoostingClassifier, RandomForestClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import average_precision_score, brier_score_loss, roc_auc_score
from sklearn.model_selection import StratifiedKFold, cross_val_predict
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

from src.features import FEATURES, TARGET, load_survey

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "survey lung cancer.csv"
OUT = ROOT / "models"
SEEDS = range(5)
TARGET_RECALL = 0.95  # below the "lower" cut-off, at most ~5% of cancer cases are missed
TARGET_SPECIFICITY = 0.90  # above the "higher" cut-off, at most ~10% of healthy people are flagged


def candidates() -> dict:
    return {
        "logistic_regression": make_pipeline(StandardScaler(), LogisticRegression(C=0.5, max_iter=1000)),
        "random_forest": RandomForestClassifier(n_estimators=300, min_samples_leaf=2, random_state=0),
        "gradient_boosting": HistGradientBoostingClassifier(max_depth=3, learning_rate=0.05, max_iter=150, random_state=0),
    }


def oof_proba(model, X, y) -> np.ndarray:
    """Out-of-fold probabilities averaged over several CV shuffles (every row scored unseen)."""
    runs = [
        cross_val_predict(model, X, y, cv=StratifiedKFold(5, shuffle=True, random_state=s), method="predict_proba")[:, 1]
        for s in SEEDS
    ]
    return np.mean(runs, axis=0)


def choose_cutoffs(y, p) -> tuple[float, float]:
    """low: highest cutoff keeping recall >= target. high: lowest cutoff reaching target specificity."""
    pos, neg = p[y == 1], p[y == 0]
    low = max(t for t in np.unique(p) if (pos >= t).mean() >= TARGET_RECALL)
    high = min((t for t in np.unique(p) if (neg < t).mean() >= TARGET_SPECIFICITY), default=1.0)
    return float(low), float(max(high, low))


def tier_table(y, p, low, high) -> dict:
    """Share of people with / without cancer landing in each tier (the 'false alarm' view)."""
    out = {}
    for name, mask in (("with_cancer", y == 1), ("without_cancer", y == 0)):
        q = p[mask]
        out[name] = {
            "lower": round(float((q < low).mean()), 3),
            "uncertain": round(float(((q >= low) & (q < high)).mean()), 3),
            "higher": round(float((q >= high).mean()), 3),
        }
    return out


def bootstrap_ci(y, p, fn, n=1000, seed=0) -> list[float]:
    rng = np.random.default_rng(seed)
    vals = []
    for _ in range(n):
        i = rng.integers(0, len(y), len(y))
        if y[i].min() != y[i].max():
            vals.append(fn(y[i], p[i]))
    return [round(float(v), 3) for v in np.percentile(vals, [2.5, 97.5])]


def write_model_card(m: dict) -> None:
    t, ci = m["tiers"], m["auc_ci95"]
    negatives = m["rows"] - m["positives"]
    comp = "\n".join(f"| {k} | {v['roc_auc']} | {v['pr_auc']} | {v['brier']} |" for k, v in m["comparison"].items())
    sex = "\n".join(f"| {k} | {v['n']} | {v['roc_auc']} |" for k, v in m["subgroups"].items())
    card = f"""# Model card: lung cancer risk screening

Generated by `python -m src.train` on {date.today()} (scikit-learn {sklearn.__version__}). Do not edit by hand.

## Intended use
Educational demo that sorts survey answers into a lower, uncertain or higher pattern. **Not a diagnosis**, not a
medical device, not validated for clinical use.

## Data
Kaggle "survey lung cancer" CSV: {m['rows']} unique respondents after removing duplicates, {m['positives']} with
lung cancer and {negatives} without. About 86% are positive, far above real-world prevalence (roughly 1-2% of
adults), so the output is a **relative score, not a probability of having cancer**. Data provenance and collection
method are undocumented.

## Model
Standardised logistic regression on {len(m['features'])} inputs ({', '.join(m['features'])}). Chosen because it
scored best in repeated 5-fold cross-validation and is exactly explainable per prediction.

| Model | ROC-AUC | PR-AUC | Brier |
| --- | --- | --- | --- |
{comp}

Chosen model ROC-AUC 95% bootstrap CI: {ci[0]} to {ci[1]}.

## Tiers (cut-offs chosen from out-of-fold scores)
Lower below {m['cutoffs']['low']:.2f}; higher at or above {m['cutoffs']['high']:.2f}; uncertain in between.

| | Lower | Uncertain | Higher |
| --- | --- | --- | --- |
| People with cancer | {t['with_cancer']['lower']:.0%} | {t['with_cancer']['uncertain']:.0%} | {t['with_cancer']['higher']:.0%} |
| People without cancer | {t['without_cancer']['lower']:.0%} | {t['without_cancer']['uncertain']:.0%} | {t['without_cancer']['higher']:.0%} |

Only {negatives} people without cancer exist in the data, so the second row is very noisy.

## Subgroups
| Group | n | ROC-AUC |
| --- | --- | --- |
{sex}

## Known limitations
- Tiny, imbalanced, unverified dataset; no external validation.
- Symptoms are self-reported and several are common (cough, fatigue, allergy).
- No smoking history detail (pack-years, quit date), the strongest real-world predictor.
- Scores do not transfer to the general population; expect many more false alarms there.
"""
    (OUT / "MODEL_CARD.md").write_text(card, encoding="utf-8")


def main() -> None:
    df = load_survey(str(DATA))
    X, y = df[FEATURES], df[TARGET].to_numpy()

    comparison, probas = {}, {}
    for name, model in candidates().items():
        p = probas[name] = oof_proba(model, X, y)
        comparison[name] = {
            "roc_auc": round(float(roc_auc_score(y, p)), 3),
            "pr_auc": round(float(average_precision_score(y, p)), 3),
            "brier": round(float(brier_score_loss(y, p)), 3),
        }
    best = "logistic_regression"  # best ROC-AUC; also the only candidate with exact explanations
    p = probas[best]
    low, high = choose_cutoffs(y, p)

    subgroups = {}
    for label, mask in (
        ("female", df.GENDER == 0),
        ("male", df.GENDER == 1),
        ("age 60+", df.AGE >= 60),
        ("age under 60", df.AGE < 60),
    ):
        mask = mask.to_numpy()
        if y[mask].min() != y[mask].max():
            subgroups[label] = {"n": int(mask.sum()), "roc_auc": round(float(roc_auc_score(y[mask], p[mask])), 3)}

    metrics = {
        "rows": int(len(df)),
        "positives": int(y.sum()),
        "model": best,
        "roc_auc": comparison[best]["roc_auc"],
        "auc_ci95": bootstrap_ci(y, p, roc_auc_score),
        "cutoffs": {"low": round(low, 4), "high": round(high, 4)},
        "tiers": tier_table(y, p, low, high),
        "comparison": comparison,
        "subgroups": subgroups,
        "sklearn_version": sklearn.__version__,
        "features": FEATURES,
    }

    model = candidates()[best].fit(X, y)
    OUT.mkdir(exist_ok=True)
    joblib.dump(model, OUT / "model.joblib")
    (OUT / "metrics.json").write_text(json.dumps(metrics, indent=2))
    write_model_card(metrics)
    print(json.dumps({k: v for k, v in metrics.items() if k != "features"}, indent=2))


if __name__ == "__main__":
    main()
